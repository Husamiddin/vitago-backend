def seed_database_if_empty(db: Session) -> int:
    existing_count = db.query(Drug).count()
    if existing_count > 0:
        return existing_count

    records: list[Drug] = []
    for group in INN_GROUPS:
        for (
            trade_name,
            trade_name_cyrl,
            dosage,
            form_uz,
            form_ru,
            manufacturer,
            country_uz,
            country_ru,
            is_local_uz,
            price_uzs,
        ) in group["items"]:
            tokens = build_search_tokens(
                trade_name,
                trade_name_cyrl,
                group["inn"],
                group["inn_uz"],
                group["inn_ru"],
            )
            records.append(
                Drug(
                    trade_name=trade_name,
                    trade_name_cyrl=trade_name_cyrl,
                    search_tokens=tokens,
                    inn=group["inn"],
                    inn_uz=group["inn_uz"],
                    inn_ru=group["inn_ru"],
                    dosage=dosage,
                    form_uz=form_uz,
                    form_ru=form_ru,
                    manufacturer=manufacturer,
                    country_uz=country_uz,
                    country_ru=country_ru,
                    is_local_uz=is_local_uz,
                    avg_price_uzs=price_uzs,
                    prescription_required="Antibiotik" in group["category_uz"] or "bosim" in group["category_uz"].lower(),
                    category_uz=group["category_uz"],
                    category_ru=group["category_ru"],
                    purpose_uz=group["purpose_uz"],
                    purpose_ru=group["purpose_ru"],
                    how_to_take_uz=group["how_to_take_uz"],
                    how_to_take_ru=group["how_to_take_ru"],
                    warnings_uz=group["warnings_uz"],
                    warnings_ru=group["warnings_ru"],
                )
            )

    db.add_all(records)
    db.commit()
    return len(records)
